#!/usr/bin/env python3
"""Inject the own sun's constants from src/proxy/own_sun_core.h into tools/effects/own_sun_lab.html.

The lab (docs/architecture/own-sun-look.md, "The tuning lab") takes its defaults from the header: this script reads the
named constants by name (the reader of verification/results/own-sun-pass/glow_meter.py) and rewrites the marked block
`/* @own_sun_constants */ ... /* @end */` of the HTML. `--check` writes nothing and fails when the block is stale.
A constant in OPTIONAL that the header does not define yet takes the value given here and is listed in HEADER_MISSING.
Usage: python3 tools/effects/generate_own_sun_lab.py [--check]
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / 'src/proxy/own_sun_core.h'
HTML = ROOT / 'tools/effects/own_sun_lab.html'
BEGIN, END = '/* @own_sun_constants */', '/* @end */'
NAMES = ('radius_default_u', 'radius_min_u', 'radius_max_u', 'radiance_default', 'radiance_min', 'radiance_max',
         'rays_default', 'rays_min', 'rays_max', 'white_mix', 'core_inner', 'corona_gain', 'corona_sigma', 'halo_gain',
         'halo_radius', 'glow_radius', 'ray_count', 'ray_gain', 'ray_length', 'ray_offset', 'ray_sigma',
         'ray_sigma_min_px', 'radius_min_px')
OPTIONAL = {'core_gain': 1.0}  # step 1d's core factor; 1 (no change) while the header lacks it
INTEGERS = ('ray_count',)
# The lab draws the quad as glow_radius core radii to each side; a header that sizes it otherwise needs a lab change.
QUAD = 'quad_extent_x = glow_radius, quad_extent_y = glow_radius'


def constant(text, name):
    """glow_meter.py's reader: `name = 1.5f` / `name = .25f` / `name = 6` as a float, None when absent."""
    match = re.search(r'\b%s = ([0-9.]+)f?\b' % name, text)
    return float(match.group(1)) if match else None


def read(text):
    values, missing = {}, []
    for name in NAMES:
        value = constant(text, name)
        if value is None:
            raise SystemExit('own_sun_core.h: constant %s not found' % name)
        values[name] = int(value) if name in INTEGERS else value
    for name, fallback in OPTIONAL.items():
        value = constant(text, name)
        if value is None:
            missing.append(name)
            value = fallback
        values[name] = value
    if QUAD not in text:
        raise SystemExit('own_sun_core.h: the quad is no longer glow_radius to each side (%r); update the lab' % QUAD)
    return values, missing


def block(values, missing):
    body = ',\n'.join('  %s: %s' % (name, json.dumps(values[name])) for name in values)
    return ('%s\n// Generated by tools/effects/generate_own_sun_lab.py from src/proxy/own_sun_core.h; do not edit by hand.\n'
            'const HEADER = {\n%s\n};\nconst HEADER_MISSING = %s;\n%s' % (BEGIN, body, json.dumps(missing), END))


def render(html, values, missing):
    start, stop = html.find(BEGIN), html.find(END)
    if start < 0 or stop < start:
        raise SystemExit('%s: marked block %s ... %s not found' % (HTML.relative_to(ROOT), BEGIN, END))
    return html[:start] + block(values, missing) + html[stop + len(END):]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail when the HTML block differs from the header')
    args = parser.parse_args()
    values, missing = read(HEADER.read_text())
    html = HTML.read_text()
    fresh = render(html, values, missing)
    if args.check:
        if fresh != html:
            print('FAIL: %s is stale against %s; run python3 tools/effects/generate_own_sun_lab.py'
                  % (HTML.relative_to(ROOT), HEADER.relative_to(ROOT)))
            return 1
        print('PASS: %s matches %s (%d constants%s)' % (HTML.relative_to(ROOT), HEADER.relative_to(ROOT), len(values),
              ', defaulted: ' + ', '.join(missing) if missing else ''))
        return 0
    if fresh != html:
        HTML.write_text(fresh)
        print('updated %s' % HTML.relative_to(ROOT))
    else:
        print('%s already current' % HTML.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
