#!/usr/bin/env python3
"""Family mean chroma of the baked fog packets, for the stored-density range.

The stored node is scalar density, so colour is one constant per family:
sum(rgb) / sum(density) over the 128^3 volume in float64, stored as float32 (the definition of
tools/analysis/fog_density_runtime_screen.py). The table is tracked because the packets are
pinned by hash in tools/fog_field_recipe.py; verification/analysis/test_fog_field_assets.py
recomputes it from a fresh bake with an independent decoder.

  fog_family_chroma.py --asset-data <build>/generated/fog_field [--check]
"""
import argparse, json, sys
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/analysis'))
sys.path.insert(0, str(ROOT / 'tools'))
import fog_distance_replay as replay  # noqa: E402
import fog_field_recipe as recipe  # noqa: E402
OUTPUT = ROOT / 'src/renderer/fog_family_chroma_inc.h'


def table(data):
    manifest = json.loads((data / 'manifest.json').read_text())
    rows = []
    for name, profile in recipe.PROFILES.items():
        volume = replay.decode_packet(data / (name + '.fogbin'), manifest)
        chroma = (volume[..., :3].sum((0, 1, 2), dtype=np.float64) / volume[..., 3].sum(dtype=np.float64)).astype(np.float32)
        rows.append((profile['id'], name, profile['atlas_sha256'], chroma))
    return sorted(rows)


def render(rows):
    lines = ['// Generated by tools/build/fog_family_chroma.py from the pinned packets; do not edit.',
             '// {profile id, mean chroma r, g, b}: sum(rgb) / sum(density) over the 128^3 volume.']
    for profile, name, atlas, chroma in rows:
        lines.append('{%du, {%sf, %sf, %sf}}, // %s, atlas %s' % (profile, *(np.format_float_positional(c, unique=True, trim='0') for c in chroma), name, atlas[:16]))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--asset-data', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='compare with the tracked table instead of writing it')
    a = parser.parse_args()
    text = render(table(a.asset_data.resolve()))
    if a.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('tracked family chroma table differs from the packets')
        print('PASS')
    else:
        OUTPUT.write_text(text); print(OUTPUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
