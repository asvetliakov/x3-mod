#!/usr/bin/env python3
"""Write the generated source-commit fragment (`*_inc.h`) for the proxy's
`proxy_identity` log line. Runs at CMake configure time and again at every
build, and rewrites the header only when the value changes, so an unchanged
tree never relinks the DLL.

The commit is `git rev-parse HEAD` with a `-dirty` suffix when any tracked or
untracked file under the build inputs differs from HEAD; `unknown` without git
or outside a work tree."""
import argparse
import subprocess
import sys
from pathlib import Path

INPUTS = ['src', 'cmake', 'tools', 'CMakeLists.txt']


def source_commit(root):
    def git(*arguments):
        return subprocess.run(['git', *arguments], cwd=root, capture_output=True, text=True, check=True).stdout.strip()
    try:
        head = git('rev-parse', 'HEAD')
        if not head:
            return 'unknown'
        dirty = git('status', '--porcelain', '--untracked-files=normal', '--', *INPUTS)
        return head + ('-dirty' if dirty else '')
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True, help='Source tree to query')
    parser.add_argument('--output', type=Path, required=True, help='Generated *_inc.h path')
    arguments = parser.parse_args()
    commit = source_commit(arguments.root.resolve())
    text = ('// Generated by tools/build/write_source_commit.py from `git rev-parse HEAD`\n'
            '// (with a -dirty suffix when the build inputs differ from HEAD, "unknown"\n'
            '// without git). Do not edit.\n'
            '#pragma once\n'
            f'#define X3M_SOURCE_COMMIT "{commit}"\n')
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    if not arguments.output.is_file() or arguments.output.read_text(encoding='utf-8') != text:
        arguments.output.write_text(text, encoding='utf-8')
        print(f'source commit: {commit}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
