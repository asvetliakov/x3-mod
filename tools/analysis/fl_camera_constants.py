#!/usr/bin/env python3
"""X3FL.exe camera-slot anchors for src/engine/fl/camera_state_fl.cpp.

Reads X3: Farnham's Legacy's X3FL.exe and writes the generated fragment
src/engine/fl/camera_state_fl_inc.h (docs/architecture/farnhams-legacy-camera.md): for the view
and the perspective matrix slot, the publication site at renderer initialization decoded as
whole instructions

    mov ecx, 0x40        ; the 64-byte allocation request
    call <allocator>     ; rel32, not relocated
    mov [slot], eax      ; a3 disp32: the publication store; the disp32 is the only relocated word
    test eax, eax        ; the null-allocation exit test

The slot RVA is derived from the store's operand (preferred VA minus the preferred ImageBase) and
must equal the documented candidate (docs/reverse-engineering/fl/camera-buffers.md, section 1) and lie
in the .data section; exactly one HIGHLOW relocation must cover the operand and none the other
bytes. At run time the DLL compares the span at module_base() + site RVA with the operand
replaced by module_base() + slot RVA. Every value is an RVA; nothing is 0x400000 based.

usage: fl_camera_constants.py [--exe PATH] [--output PATH] [--check] [--json]
  --check  exit 1 when the fragment on disk differs from the generated text
  --json   print the decoded anchors and exit (verification/analysis/test_fl_camera_state.py)
"""
import argparse
import hashlib
import importlib.util
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_EXE = Path('/mnt/c/X3FL/X3FL.exe')
DEFAULT_OUTPUT = ROOT / 'src/engine/fl/camera_state_fl_inc.h'
_spec = importlib.util.spec_from_file_location('fl_identity_constants', ROOT / 'tools/analysis/fl_identity_constants.py')
identity = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(identity)

# (name, site RVA of `mov ecx, 0x40`, documented slot RVA). camera-buffers.md: view request 0x4da01a,
# publication 0x4da024, slot 0x5aae68; perspective request 0x4da036, publication 0x4da040, slot 0x5aae78.
SITES = (('view', 0x0da01a, 0x1aae68), ('projection', 0x0da036, 0x1aae78))
ORTHOGRAPHIC_SLOT_RVA = 0x1aae4c  # the orthographic-path projection slot (allocation 0x4da05e): never the one read
OPERAND_OFFSET = 11  # mov ecx,imm32 (5) + call rel32 (5) + a3 (1)
LENGTH = 17          # ... + disp32 (4) + test eax,eax (2)


def decode_site(data, fields, name, site_rva, expected_slot_rva):
    """The anchor span at site_rva as whole instructions; raises on any deviation from the documented shape."""
    off = identity.rva_to_offset(fields, site_rva)
    span = data[off:off + LENGTH]
    if span[0:5] != b'\xb9\x40\x00\x00\x00':
        raise ValueError(f'{name}: no `mov ecx, 0x40` at 0x{site_rva:x}')
    if span[5] != 0xe8:
        raise ValueError(f'{name}: no call rel32 at 0x{site_rva + 5:x}')
    rel = struct.unpack_from('<i', span, 6)[0]
    allocator_rva = (site_rva + 10 + rel) & 0xffffffff
    if span[10] != 0xa3:
        raise ValueError(f'{name}: no `mov [disp32], eax` at 0x{site_rva + 10:x}')
    operand_va = struct.unpack_from('<I', span, OPERAND_OFFSET)[0]
    slot_rva = operand_va - fields['image_base']
    if slot_rva != expected_slot_rva:
        raise ValueError(f'{name}: store operand 0x{operand_va:x} is slot RVA 0x{slot_rva:x}, documented 0x{expected_slot_rva:x}')
    if span[15:17] != b'\x85\xc0':
        raise ValueError(f'{name}: no `test eax, eax` at 0x{site_rva + 15:x}')
    data_section = next(s for s in fields['sections'] if s[0].rstrip(b'\0') == b'.data')
    if not data_section[2] <= slot_rva < data_section[2] + data_section[1] - 4:
        raise ValueError(f'{name}: slot RVA 0x{slot_rva:x} outside .data')
    operand_rva = site_rva + OPERAND_OFFSET
    touching = [r for r in identity.relocated_rvas(data, fields) if r < site_rva + LENGTH and site_rva < r + 4]
    if touching != [operand_rva]:
        raise ValueError(f'{name}: relocations in the span are {[hex(r) for r in touching]}, expected [0x{operand_rva:x}]')
    masked = bytearray(span)
    masked[OPERAND_OFFSET:OPERAND_OFFSET + 4] = b'\0\0\0\0'
    return {'name': name, 'site_rva': site_rva, 'slot_rva': slot_rva, 'operand_offset': OPERAND_OFFSET,
            'length': LENGTH, 'bytes': bytes(masked), 'allocator_rva': allocator_rva, 'file_bytes': span}


def anchors(data, fields):
    out = [decode_site(data, fields, *site) for site in SITES]
    if len({a['allocator_rva'] for a in out}) != 1:
        raise ValueError('the two publication sites call different allocators')
    return out


def fragment(data, fields):
    found = anchors(data, fields)
    lines = [
        '// Generated by tools/analysis/fl_camera_constants.py from X3FL.exe; do not edit.',
        f'// X3FL.exe SHA-256 {hashlib.sha256(data).hexdigest()} (provenance, never a gate).',
        '// Each anchor is the renderer-initialization publication of one 64-byte matrix buffer, decoded as whole',
        '// instructions: mov ecx,0x40; call <allocator>; mov [slot],eax; test eax,eax. `bytes` hold the span with',
        '// the relocated disp32 zeroed; at run time it reads module_base() + slot_rva. Every value is an RVA.',
        f'// Allocator RVA 0x{found[0]["allocator_rva"]:08x} (rel32 inside the span, not relocated).',
        '// clang-format off',
    ]
    for a in found:
        hex_bytes = ', '.join(f'0x{b:02x}' for b in a['bytes'])
        lines.append(f'constexpr CameraAnchor {a["name"]}_anchor = {{0x{a["site_rva"]:08x}, 0x{a["slot_rva"]:08x}, '
                     f'{a["operand_offset"]}, {a["length"]}, {{{hex_bytes}}}}};')
    lines.append(f'constexpr std::uint32_t orthographic_slot_rva = 0x{ORTHOGRAPHIC_SLOT_RVA:08x}; // never read; documented negative')
    lines.append('// clang-format on')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--exe', type=Path, default=DEFAULT_EXE)
    ap.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--json', action='store_true')
    args = ap.parse_args()
    data = args.exe.read_bytes()
    fields = identity.parse(data)
    if args.json:
        out = []
        for a in anchors(data, fields):
            row = dict(a)
            row['bytes'] = a['bytes'].hex()
            row['file_bytes'] = a['file_bytes'].hex()
            out.append(row)
        print(json.dumps({'sha256': hashlib.sha256(data).hexdigest(), 'image_base': fields['image_base'],
                          'orthographic_slot_rva': ORTHOGRAPHIC_SLOT_RVA, 'anchors': out}))
        return 0
    text = fragment(data, fields)
    if args.check:
        same = args.output.exists() and args.output.read_text() == text
        print('fl_camera_constants', 'match' if same else 'differs', args.output)
        return 0 if same else 1
    args.output.write_text(text)
    print('wrote', args.output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
