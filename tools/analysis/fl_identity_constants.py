#!/usr/bin/env python3
"""X3FL.exe identity constants for src/engine/fl/executable_identity_fl.h.

Reads the PE headers of X3: Farnham's Legacy's X3FL.exe and writes the generated
fragment src/engine/fl/executable_identity_fl_inc.h (docs/architecture/farnhams-legacy-build.md):
link stamp, entry point RVA, SizeOfImage, preferred ImageBase (provenance only:
the image is ASLR-relocatable), file characteristics without the LAA bit, file
size, the section table, and one entry anchor: the first ANCHOR_LENGTH bytes at
the entry point RVA, refused when any base relocation touches them (the bytes
must read the same at any load base). Every value is an RVA or a size; nothing
is 0x400000 based.

usage: fl_identity_constants.py [--exe PATH] [--output PATH] [--check] [--json]
  --check  exit 1 when the fragment on disk differs from the generated text
  --json   print the parsed fields of --exe (any PE32 image) and exit; used by
           verification/analysis/test_fl_identity.py
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_EXE = Path('/mnt/c/X3FL/X3FL.exe')
DEFAULT_OUTPUT = ROOT / 'src/engine/fl/executable_identity_fl_inc.h'
LAA_BIT = 0x0020
ANCHOR_LENGTH = 10


def parse(data):
    """The PE32 fields the FL identity compares, from the file bytes."""
    if data[:2] != b'MZ':
        raise ValueError('no MZ header')
    nt = struct.unpack_from('<I', data, 0x3c)[0]
    if data[nt:nt + 4] != b'PE\0\0':
        raise ValueError('no PE signature')
    machine, nsec, stamp, _, _, opt_size, chars = struct.unpack_from('<HHIIIHH', data, nt + 4)
    opt = nt + 24
    magic = struct.unpack_from('<H', data, opt)[0]
    if magic != 0x10b:
        raise ValueError('not PE32')
    entry = struct.unpack_from('<I', data, opt + 16)[0]
    image_base = struct.unpack_from('<I', data, opt + 28)[0]
    image_size = struct.unpack_from('<I', data, opt + 56)[0]
    size_of_headers = struct.unpack_from('<I', data, opt + 60)[0]
    dll_chars = struct.unpack_from('<H', data, opt + 70)[0]
    reloc_rva, reloc_size = struct.unpack_from('<II', data, opt + 96 + 5 * 8)
    sections = []
    for i in range(nsec):
        off = opt + opt_size + 40 * i
        name = data[off:off + 8]
        vsize, va, raw_size, raw_ptr = struct.unpack_from('<IIII', data, off + 8)
        sec_chars = struct.unpack_from('<I', data, off + 36)[0]
        sections.append((name, vsize, va, raw_size, raw_ptr, sec_chars))
    return {'machine': machine, 'time_date_stamp': stamp, 'optional_header_size': opt_size,
            'characteristics': chars, 'characteristics_without_laa': chars & ~LAA_BIT & 0xffff,
            'magic': magic, 'entry_point': entry, 'image_base': image_base, 'image_size': image_size,
            'size_of_headers': size_of_headers, 'nt_offset': nt, 'dll_characteristics': dll_chars, 'reloc_rva': reloc_rva, 'reloc_size': reloc_size,
            'sections': sections, 'file_size': len(data)}


def rva_to_offset(fields, rva):
    for name, vsize, va, raw_size, raw_ptr, _ in fields['sections']:
        if va <= rva < va + max(vsize, raw_size):
            return raw_ptr + rva - va
    raise ValueError(f'rva 0x{rva:x} outside every section')


def relocated_rvas(data, fields):
    """Every RVA a HIGHLOW (type 3) base relocation rewrites (4 bytes each)."""
    out = []
    if not fields['reloc_size']:
        return out
    pos = rva_to_offset(fields, fields['reloc_rva'])
    end = pos + fields['reloc_size']
    while pos + 8 <= end:
        page, block = struct.unpack_from('<II', data, pos)
        if block < 8:
            break
        for k in range((block - 8) // 2):
            entry = struct.unpack_from('<H', data, pos + 8 + 2 * k)[0]
            kind, offset = entry >> 12, entry & 0xfff
            if kind == 3:
                out.append(page + offset)
            elif kind != 0:
                raise ValueError(f'unexpected relocation type {kind}')
        pos += block
    return out


def anchor(data, fields):
    rva = fields['entry_point']
    for r in relocated_rvas(data, fields):
        if r < rva + ANCHOR_LENGTH and rva < r + 4:
            raise ValueError(f'relocation at 0x{r:x} overlaps the entry anchor')
    off = rva_to_offset(fields, rva)
    return rva, data[off:off + ANCHOR_LENGTH]


def fragment(data, fields):
    rva, anchor_bytes = anchor(data, fields)
    lines = [
        '// Generated by tools/analysis/fl_identity_constants.py from X3FL.exe; do not edit.',
        f'// X3FL.exe SHA-256 {hashlib.sha256(data).hexdigest()} (provenance, never a gate).',
        f'// Preferred ImageBase 0x{fields["image_base"]:08x}, DllCharacteristics 0x{fields["dll_characteristics"]:04x}'
        ' (provenance: the image is relocatable; every value below is an RVA or a size).',
        f'constexpr std::uint32_t image_size = 0x{fields["image_size"]:08x}, entry_point = 0x{fields["entry_point"]:08x},'
        f' time_date_stamp = 0x{fields["time_date_stamp"]:08x};',
        f'constexpr std::uint16_t characteristics_without_laa = 0x{fields["characteristics_without_laa"]:04x};',
        f'constexpr unsigned long long file_size = {fields["file_size"]};',
        '// clang-format off',
        'constexpr Section sections[] = {',
    ]
    rows = []
    for name, vsize, va, raw_size, raw_ptr, chars in fields['sections']:
        chars_list = ','.join(f"'{chr(b)}'" if b else '0' for b in name)
        rows.append(f'    {{{{{chars_list}}}, 0x{vsize:08x}, 0x{va:08x}, 0x{raw_size:08x}, 0x{raw_ptr:08x}, 0x{chars:08x}}}')
    lines.append(',\n'.join(rows) + '};')
    lines.append(f'// The first {ANCHOR_LENGTH} bytes at the entry point RVA; no base relocation touches them.')
    hex_bytes = ', '.join(f'0x{b:02x}' for b in anchor_bytes)
    lines.append(f'constexpr std::uint32_t entry_anchor_rva = 0x{rva:08x};')
    lines.append(f'constexpr std::uint8_t entry_anchor[{ANCHOR_LENGTH}] = {{{hex_bytes}}};')
    lines.append('// clang-format on')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--exe', type=Path, default=DEFAULT_EXE)
    ap.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--json', action='store_true')
    args = ap.parse_args()
    data = args.exe.read_bytes()
    fields = parse(data)
    if args.json:
        out = dict(fields)
        out['sections'] = [[n.rstrip(b'\0').decode('latin-1'), *rest] for n, *rest in fields['sections']]
        out['sha256'] = hashlib.sha256(data).hexdigest()
        try:
            rva, anchor_bytes = anchor(data, fields)
            out['entry_anchor'] = anchor_bytes.hex()
        except ValueError as error:
            out['entry_anchor'] = None
            out['entry_anchor_error'] = str(error)
        print(json.dumps(out))
        return 0
    text = fragment(data, fields)
    if args.check:
        same = args.output.exists() and args.output.read_text() == text
        print('fl_identity_constants', 'match' if same else 'differs', args.output)
        return 0 if same else 1
    args.output.write_text(text)
    print('wrote', args.output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
