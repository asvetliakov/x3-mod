// src/proxy/chase_transition.cpp). Facts: docs/reverse-engineering/fl/chase-transition.md (offline study, then
// "Verified 2026-11-02 against X3FL.exe"); verifier verification/probe/verify_chase_transition_sites_fl.py, which also
// emits the window rows below (--emit-windows). X3FL.exe is relocatable: every value is an RVA added to
