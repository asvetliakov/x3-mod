// the handlers normalize native return addresses to before the portable restore core compares them. No Windows
// dependency (the native fixture compiles it).
//
// Twelve claimed spans, all whole instructions with no relative control flow, no direct edge and no relocated pointer
// into an interior (the EH adapter's start is published once, at 0x0bed96, by the interpreter's SEH registration):
//   0 construct   0x020ec0  push ebx; mov ebx,esp; sub esp,8        ECX = cockpit, [ESP] = caller return
