//   3 begin       0x021f50  push ebp; mov ebp,esp; and esp,-16     ECX = cockpit, frame = entry ESP
//   4/5 exits     0x022f9b / 0x022fa9  pop edi; pop esi; pop ebx; mov esp,ebp   entry ESP = EBP + 4
//   6 mode store  0x031abc  mov [eax+0x150],ecx    EAX = cockpit, ECX = mode, EBX = dispatcher argument frame
//   7 load store  0x01bf6e  mov [edi+0x150],edx    EDI = cockpit, EDX = mode
//   restore 0 inject     0x0cfd00  push ebp; mov ebp,esp; and esp,-16   ECX = the controlled object
