constexpr std::uint32_t fnv1a(const std::uint8_t* p, unsigned n) {
    std::uint32_t h = 0x811c9dc5u;
    for (unsigned i = 0; i < n; ++i) h = (h ^ p[i]) * 0x01000193u;
    return h;
}
constexpr std::uint32_t le32(const std::uint8_t* b) {
    return std::uint32_t(b[0]) | std::uint32_t(b[1]) << 8 | std::uint32_t(b[2]) << 16 | std::uint32_t(b[3]) << 24;
}
// Native return address -> preferred-base VA (0 outside the image): the form the restore core's callers carry.
constexpr std::uint32_t preferred(std::uint32_t address, std::uintptr_t base) {
    return base && address - std::uint32_t(base) < image_size ? address - std::uint32_t(base) + preferred_base : 0;
}
// Every window at the loaded base, before any write. Read is bool(std::uintptr_t address, void* out, unsigned n).
// nullptr when all match (each fixup dword equal to base + its target RVA, the rest byte-exact); else the refusal,
// with *failed the window index.
template <class Read> const char* plan(std::uintptr_t base, Read read, unsigned* failed) {
    *failed = window_count;
    if (!base || (base & 0xffff)) return "invalid_base";
    for (unsigned w = 0; w < window_count; ++w) {
        const Window& win = windows[w];
        std::uint8_t now[max_window]{};
        *failed = w;
        if (!read(base + win.rva, now, win.length)) return "window_unreadable";
        for (unsigned f = 0; f < win.fixups; ++f) {
            if (le32(now + win.fixup[f].offset) != std::uint32_t(base + win.fixup[f].target_rva)) return "fixup_mismatch";
            std::memset(now + win.fixup[f].offset, 0, 4);
        }
        if (std::memcmp(now, win.bytes, win.length)) return "window_mismatch";
    }
    *failed = window_count;
    return nullptr;
}
// The expected bytes of a span at this base (the relocated dword filled in).
inline void expected(const SiteRow& s, std::uintptr_t base, std::uint8_t* out) {
    std::memcpy(out, s.bytes, s.length);
    if (s.reloc_offset >= 0) {
        const std::uint32_t v = std::uint32_t(base + s.reloc_target_rva);
        std::memcpy(out + s.reloc_offset, &v, 4);
    }
}

constexpr bool windows_measured() {
    for (unsigned w = 0; w < window_count; ++w)
        if (windows[w].length > max_window || windows[w].fixups > max_fixups ||
            fnv1a(windows[w].bytes, windows[w].length) != windows[w].fnv1a)
            return false;
    return true;
}
static_assert(windows_measured(), "every window is the measured one (FNV-1a, fixups zeroed)");
constexpr bool span_in_window(const SiteRow& s) {
    const Window& w = windows[s.window];
    if (s.rva != w.rva + s.window_offset || s.window_offset + s.length > w.length) return false;
    for (unsigned i = 0; i < s.length; ++i)
        if (s.bytes[i] != w.bytes[s.window_offset + i]) return false;
    if (s.reloc_offset >= 0) {
        bool fixed = false;
        for (unsigned f = 0; f < w.fixups; ++f)
            fixed |= w.fixup[f].offset == s.window_offset + unsigned(s.reloc_offset) &&
                     w.fixup[f].target_rva == s.reloc_target_rva;
        if (!fixed) return false;
    }
    return s.length >= 5 && s.length <= 8;
}
constexpr bool spans_in_windows() {
    for (const SiteRow& s : sites)
        if (!span_in_window(s)) return false;
    for (const SiteRow& s : restore_sites)
        if (!span_in_window(s)) return false;
    return true;
}
