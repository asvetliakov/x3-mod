constexpr std::uint32_t fnv1a(const unsigned char* p, unsigned n) {
    std::uint32_t h = 0x811c9dc5u;
    for (unsigned i = 0; i < n; ++i) h = (h ^ p[i]) * 0x01000193u;
    return h;
}
constexpr std::uint32_t le32(const unsigned char* b) {
    return std::uint32_t(b[0]) | std::uint32_t(b[1]) << 8 | std::uint32_t(b[2]) << 16 | std::uint32_t(b[3]) << 24;
}
// The byte at `rva` inside window w (static checks below).
constexpr unsigned char window_byte(WindowIndex w, std::uint32_t rva) {
    return windows[w].bytes[rva - windows[w].rva];
}
// The install decision: every window read at base + RVA through `read(address, out, size)` must equal the expected
// bytes with each relocated dword equal to base + its target RVA. nullptr when all match, else the first refused
// window's name (the reason is in *why: unreadable, slot_mismatch or window_mismatch).
template <class Read> const char* refused_window(std::uintptr_t base, Read read, const char** why) {
    *why = nullptr;
    if (!base || (base & 0xffff)) {
        *why = "invalid_base";
        return "base";
    }
    for (const Window& w : windows) {
        unsigned char now[max_window]{};
        if (!read(base + w.rva, now, w.length)) {
            *why = "unreadable";
            return w.name;
        }
        for (unsigned r = 0; r < w.reloc_count; ++r) {
            if (le32(now + w.reloc_offset[r]) != std::uint32_t(base + w.reloc_target[r])) {
                *why = "slot_mismatch";
                return w.name;
            }
            std::memset(now + w.reloc_offset[r], 0, 4);
        }
        if (std::memcmp(now, w.bytes, w.length)) {
            *why = "window_mismatch";
            return w.name;
        }
    }
    return nullptr;
}

