static_assert(W::measured(windows), "every window is the measured one (FNV-1a, fixups zeroed)");
constexpr bool contract_anchored() {
    const W::Window& c = windows[window_ti_case];
    const unsigned at = hook_rva - case_rva;
    if (c.rva != case_rva || at != 7 || hook_next_rva != hook_rva + hook_length) return false;
    for (unsigned i = 0; i < hook_length; ++i)
        if (c.bytes[at + i] != hook_bytes[i]) return false;
    if (!W::has_fixup(c, at + hook_reloc_offset, cfg_slot_rva) || !W::has_fixup(c, 23, vm_slot_rva) ||
        c.bytes[0] != 0x8b || c.bytes[3] != 0x24 || c.bytes[4] != 0x6a || c.bytes[6] != 0x56 ||
        c.bytes[hook_next_rva - case_rva + 2] != cfg_factor)
        return false; // mov eax,[esp+0x24]; push 1; push esi; ...; mov [eax+0xbc],ecx
    if (!W::has_fixup(windows[window_ti_table_entry], 0, case_rva)) return false;
    if (windows[window_wrapper].rva != script_call_rva || windows[window_wrapper].bytes[0] != 0x83) return false;
    if (windows[window_callback_bound_ok].bytes[0x12] != callback_none ||
        windows[window_callback_bound_fail].bytes[0x1d] != callback_none)
        return false; // cmp edx,0x20 / cmp eax,0x20
    if (!W::has_fixup(windows[window_stop_call], 5, windows[window_stop_name].rva)) return false;
    if (!W::has_fixup(windows[window_manager], 1, manager_slot_rva) || windows[window_manager].bytes[7] != manager_player ||
        windows[window_manager].bytes[14] != 0x54)
        return false; // mov eax,[manager]; mov eax,[eax+0x38]; test; je; cmp [eax+0x54],edx
    const W::Window& pause = windows[window_pause];
    if (!W::has_fixup(pause, 2, game_root_rva) || !W::has_fixup(pause, 12, ring_read_rva) ||
        pause.bytes[18] != (game_pause & 0xff) || pause.bytes[19] != (game_pause >> 8) || pause.bytes[24] != pause_bit)
        return false;
    const W::Window& inject = windows[window_inject_head];
    // the window starts after the six prologue bytes chase_transition claims (its own windows cover those), so the
    // compare holds whichever module claimed the shared entry first
    if (inject.rva != inject_rva + 6 || !W::has_fixup(inject, 5, input_ctx_slot_rva) ||
        !W::has_fixup(inject, 27, action_counters_rva))
        return false;
    if (!W::has_fixup(windows[window_counter_increment], 9, action_counters_rva)) return false;
    if (!W::has_fixup(windows[window_ring_reader], 3, ring_ri_rva) ||
        !W::has_fixup(windows[window_ring_reader], 10, ring_wi_rva) ||
        !W::has_fixup(windows[window_ring_slots], 4, ring_slots_rva))
        return false;
    if (!W::has_fixup(windows[window_ship_script], 5, manager_slot_rva)) return false;
    for (unsigned w = 0; w < window_count; ++w)
        if (windows[w].part != 0) return false;
    return true;
}
static_assert(contract_anchored(), "the hook, the call, the roots and the latch scalars lie in their compared windows");
static_assert((hook_rva & 7u) + 5u > 8u, "the hook's jump straddles an aligned qword: plain write, emitted check");
// Whether a five-byte jump at this address straddles an aligned qword (engine_patch then takes the plain copy).
constexpr bool straddles_qword(std::uint32_t address) {
    return (address & 7u) + 5u > 8u;
}
// The live expected bytes of the hook at this base (the HIGHLOW filled in).
inline void expected_hook(std::uintptr_t base, std::uint8_t out[hook_length]) {
    std::memcpy(out, hook_bytes, hook_length);
    const std::uint32_t cfg = std::uint32_t(base + cfg_slot_rva);
    std::memcpy(out + hook_reloc_offset, &cfg, 4);
}
