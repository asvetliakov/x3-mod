// FL edition of the SETA restore / key-latch native contract (the AP twin is src/proxy/seta_restore_core.h and
// seta_key_latch_core.h, whose state machine, story recognition, return scan, latch and their bounds are shared
// unchanged). Facts: docs/reverse-engineering/fl/seta.md sections 1 to 3, "Port (2026-11-03)"; verifier
// verification/probe/verify_seta_restore_sites_fl.py (which emits the window rows below, --emit-windows). X3FL.exe is
// relocatable: every value is an RVA added to x3m::fl::module_base(), or a field offset. No Windows dependency.
//
// Factor hook, TI_SetTimeWarpFactor's case (dispatcher case table entry 9 -> 0x0ce097):
//   0ce097  mov eax,[esp+0x24]        EAX = argument cells (tag byte, int32 at +1)
//   0ce09b  push 1; push esi          two pending native words (ESI = task, from the dispatcher's [esp+0x14])
//   0ce09e  mov ecx,[eax+1]           <- claimed, 8 bytes (3 + 5): the new factor
//   0ce0a1  mov eax,[base+0x1a83b0]   the cfg pointer (HIGHLOW at +4: the claim's expected bytes and its tail are the
//                                       live relocated instruction, bound to the base before the claim)
//   0ce0a6  mov [eax+0xbc],ecx        the continuation (the store the handler reads the old value before)
// The span starts at qword offset 6: its five jump bytes straddle an aligned qword, so engine_patch takes the plain
// copy (inside the install window) and the module reads the jump back before chaining (emitted check). Handler
// arguments (EAX = args, ESI = task); every GPR, EFLAGS, DF, XMM0..7, the x87 image, MXCSR and LastError preserved.
//
// The injected call: the SETA wrapper 0x0bb500 (cdecl, six words: selector -> ECX and token -> EDX for the preparation
// 0x0bb310, which stores them at task +0x30/+0x34; key, name, result kind, argc), AL 0 when the receiver or method does
// not resolve, else a tail-jump to 0x0bb470 (bottom cells, the interpreter 0x0bed90, AL 1 after a normal return: accepted
// dispatch, not a completed ramp). Selector 32 is the callback-free value: both completions bound it with
// `cmp ...,0x20; jge` before the callback table (0 is a real engine callback slot, the native input stop's choice).
// The shared injection site, its VM clear/load and EH cancel sites are chase_transition's (chase_transition_sites_fl.h).
