// ---- the per-axis decision at the loaded base (the AP evaluate with the FL bindings) ----
// The engine reads of one stub call, on the main thread at the span, where the native instructions read the same cfg
// pointer, cfg+0x704 and record+0x24: plain loads, as valid as theirs. The register is checked first: a rotation's EDI
// must be the axis's record, a strafe's ESI the cfg pointer (another value: contract, original path).
inline core::Skip evaluate(unsigned axis, std::uint32_t reg, std::uintptr_t base, core::Inputs& in,
                           core::Out& out) noexcept {
    out = core::Out{};
    in = core::Inputs{};
    if (axis >= core::axis_count || !base) return core::contract;
    const std::uint32_t cfg = core::load32(std::uint32_t(base + cfg_slot_rva));
    if (!cfg) return core::contract;
    if (sites[axis].record_rva ? reg != std::uint32_t(base + sites[axis].record_rva) : reg != cfg) return core::contract;
    in.factor = std::int32_t(core::load32(cfg + cfg_factor));
    in.governor = std::int32_t(core::load32(cfg + cfg_governor));
    in.game_ms = std::int32_t(core::load32(cfg + cfg_game_ms));
    in.target = sites[axis].record_rva ? std::int32_t(core::load32(reg + record_target)) : 0;
    in.mouse_x = core::load32(std::uint32_t(base + mouse_type_x_rva));
    in.mouse_y = core::load32(std::uint32_t(base + mouse_type_y_rva));
    in.mouse_turret_x = core::load32(std::uint32_t(base + mouse_turret_x_rva));
    in.mouse_turret_y = core::load32(std::uint32_t(base + mouse_turret_y_rva));
    return core::decide(axis, in, out);
}
// The apply path's multiplier of the span's double: rotation 1/k^2 (the step), strafe 1/k (the limit).
inline double step_scale(unsigned axis, const core::Out& out) noexcept {
    return axis < core::strafe_y ? out.inv_k * out.inv_k : out.inv_k;
}
