static_assert(W::measured(windows), "every window is the measured one (FNV-1a, fixups zeroed)");
constexpr bool spans_in_windows() {
    for (unsigned r = 0; r < stop_row_count; ++r) {
        const W::Window& w = windows[window_stop_yaw + r];
        if (w.rva != stop_rows_rva + r * stop_row_length || w.length != stop_row_length || w.fixups != 1 ||
            w.fixup[0].offset != 2 || w.part != 1)
            return false;
    }
    for (unsigned i = 0; i < stop_patch_count; ++i) {
        const W::Window& w = windows[i < stop_speed_row ? i : stop_speed_row + 1];
        if (w.bytes[stop_jcc_offset] != stop_patches[i].original[0] ||
            w.bytes[stop_jcc_offset + 1] != stop_patches[i].original[1])
            return false;
    }
    // the speed row keeps its JNE to the stop
    const W::Window& speed = windows[window_stop_speed];
    if (speed.bytes[stop_jcc_offset] != 0x75 || stop_rows_rva + stop_speed_row * stop_row_length + 9 +
                                                        speed.bytes[stop_jcc_offset + 1] != stop_rva)
        return false;
    const W::Window& block = windows[window_stop_block];
    if (block.rva != stop_rva || !W::has_fixup(block, 1, cfg_slot_rva) || block.bytes[5] != 0x81 ||
        block.bytes[7] != cfg_factor || block.bytes[13] != 0x01 || block.rva + stop_join_rva - stop_rva !=
        stop_join_rva || block.bytes[stop_join_rva - stop_rva] != 0xf7)
        return false;
    for (unsigned a = 0; a < core::axis_count; ++a) {
        const Site& s = sites[a];
        const W::Window& w = windows[s.window];
        if (w.part != 2 || s.rva != w.rva + s.window_offset || s.window_offset + s.length > w.length) return false;
        for (unsigned i = 0; i < s.length; ++i)
            if (w.bytes[s.window_offset + i] != s.bytes[i]) return false;
        for (unsigned f = 0; f < w.fixups; ++f) // no relocated dword inside a claimed span
            if (w.fixup[f].offset + 4 > s.window_offset && w.fixup[f].offset < s.window_offset + s.length) return false;
        if (a < core::strafe_y && (!W::has_fixup(w, 150, cfg_slot_rva) || w.bytes[0x0b] != 0x8b || w.bytes[0x0c] != 0xf9))
            return false; // the controller loads cfg and takes EDI = ECX = record
    }
    const W::Window& calls = windows[window_axis_calls];
    if (!W::has_fixup(calls, 2, sites[0].record_rva) || !W::has_fixup(calls, 13, sites[1].record_rva) ||
        !W::has_fixup(calls, 24, sites[2].record_rva))
        return false;
    const W::Window& strafe = windows[window_strafe_block];
    if (!W::has_fixup(strafe, 8, cfg_slot_rva)) return false;
    const W::Window& mouse = windows[window_mouse_dispatch];
    if (!W::has_fixup(mouse, 18, mouse_turret_x_rva) || !W::has_fixup(mouse, 27, mouse_type_x_rva) ||
        !W::has_fixup(mouse, 69, sites[0].record_rva) || !W::has_fixup(mouse, 86, sites[1].record_rva) ||
        !W::has_fixup(mouse, 103, sites[2].record_rva))
        return false;
    return mouse_type_y_rva == mouse_type_x_rva + 4 && mouse_turret_y_rva == mouse_turret_x_rva + 4 &&
           W::le32(windows[window_angle_scale].bytes) == 0x37800000u &&
           W::le32(windows[window_strafe_limit].bytes) == 0x469c4000u &&
           W::le32(windows[window_milli].bytes) == 0xd2f1a9fcu && W::le32(windows[window_milli].bytes + 4) == 0x3f50624du;
}
