// ---- part A ----
struct Patch {
    const char* name;
    std::uint32_t rva;
    unsigned char original[2];
    unsigned char patched[2];
};
constexpr unsigned stop_patch_count = 8, stop_row_count = 9, stop_row_length = 9, stop_jcc_offset = 7,
                   stop_speed_row = 7;
constexpr std::uint32_t stop_rows_rva = 0x0d217f, stop_rva = 0x0d21d0, stop_join_rva = 0x0d21fb;
constexpr Patch stop_patches[stop_patch_count] = {
    {"seta_manual_flight_stop_yaw_fl", 0x0d2186, {0x75, 0x48}, {0x66, 0x90}},
    {"seta_manual_flight_stop_pitch_fl", 0x0d218f, {0x75, 0x3f}, {0x66, 0x90}},
    {"seta_manual_flight_stop_roll_fl", 0x0d2198, {0x75, 0x36}, {0x66, 0x90}},
    {"seta_manual_flight_stop_turret_yaw_fl", 0x0d21a1, {0x75, 0x2d}, {0x66, 0x90}},
    {"seta_manual_flight_stop_turret_pitch_fl", 0x0d21aa, {0x75, 0x24}, {0x66, 0x90}},
    {"seta_manual_flight_stop_strafe_x_fl", 0x0d21b3, {0x75, 0x1b}, {0x66, 0x90}},
    {"seta_manual_flight_stop_strafe_y_fl", 0x0d21bc, {0x75, 0x12}, {0x66, 0x90}},
    {"seta_manual_flight_stop_look_fl", 0x0d21ce, {0x74, 0x2b}, {0xeb, 0x2b}},
};
constexpr unsigned stop_straddling = 1; // the pitch JNE: plain write (emitted check), the other seven atomic
// The span the eight writes lie in, for the protection calls.
constexpr std::uint32_t stop_span_rva = 0x0d2186;
constexpr unsigned stop_span_length = stop_rva - stop_span_rva;
constexpr bool straddles(std::uint32_t rva, unsigned n) {
    return (rva & 7u) + n > 8u; // the module base is 64 KB aligned: an RVA's qword geometry is the VA's
}
constexpr bool stop_patches_well_formed() {
    if ((stop_span_rva + stop_span_length - 1) >> 12 != stop_span_rva >> 12) return false;
    for (unsigned i = 0; i < stop_patch_count; ++i) {
        const Patch& p = stop_patches[i];
        const unsigned row = i < stop_speed_row ? i : stop_speed_row + 1; // the look row follows the speed row
        if (p.rva != stop_rows_rva + row * stop_row_length + stop_jcc_offset || p.rva < stop_span_rva ||
            p.rva + 2 > stop_span_rva + stop_span_length || straddles(p.rva, 2) != (i == stop_straddling))
            return false;
        const std::uint32_t target = p.rva + 2 + p.original[1];
        if (i < stop_speed_row ? (p.original[0] != 0x75 || target != stop_rva || p.patched[0] != 0x66 || p.patched[1] != 0x90)
                               : (p.original[0] != 0x74 || target != stop_join_rva || p.patched[0] != 0xeb ||
                                  p.patched[1] != p.original[1]))
            return false;
    }
    return true;
}
static_assert(stop_patches_well_formed(),
              "eight two-byte Jcc rewrites at the rows' Jcc in one page; only the pitch row straddles a qword");

