// FL edition of the SETA manual-flight sites (the AP twin is src/proxy/seta_manual_flight_core.h, whose per-axis
// decision core::decide -- the factor > 1.0 gate, the mouse-delta exclusion, R = (factor * governor + 0x8000) >> 16 in
// 0x10001..0x7fffffff, k = R / 65536, round(target / k) half away from zero -- is shared unchanged). Facts:
// docs/reverse-engineering/fl/seta.md sections 3 and 4, "Port (2026-11-03)"; verifier
// verification/probe/verify_seta_manual_flight_sites_fl.py (which emits the window rows below, --emit-windows). X3FL.exe is
// relocatable: every value is an RVA added to x3m::fl::module_base(), or a field offset. No Windows dependency.
//
// Part A, the input routine's stop rows (0x0d217f, nine rows of 9 bytes: `cmp dword [record+0x10],0` (7, the flag a
// HIGHLOW) + short Jcc at row+7): yaw, pitch, roll, turret yaw, turret pitch, strafe X, strafe Y, speed (JNE kept),
// look (JE 0x0d21fb). The seven non-speed JNE 0x0d21d0 become `66 90`, the look JE becomes JMP (`eb`, same rel8): only
// the speed flag reaches 0x0d21d0 (`mov eax,[cfg]; cmp [eax+0xbc],0x10000; je 0x0d21fb`, then the native
// `0x0bb500(0,0,0x96,"StopFastForward",1,0)`). All eight lie in [0x0d2186, 0x0d21d0), one page; 0x0d218f (the pitch JNE)
// starts at qword offset 7, so its two bytes straddle an aligned qword: engine_patch::write_code takes the plain copy
// there (inside the install window, read back), the other seven fit one qword (lock cmpxchg8b).
//
// Part B, five SSE spans (no relocation, no relative flow, entered only at their first byte):
//   yaw   0x0ce878 / pitch 0x0ceb88 / roll 0x0ced98, 16 bytes each, continuation +16:
//         cvtpd2ps xmm3,xmm0; movd xmm0,[edi+0x24]; cvtdq2ps xmm0,xmm0; mulss xmm0,xmm4
//         EDI = record (0x21c6c0 / 0x21c6e8 / 0x21c710, `mov edi,ecx` in each controller), ESI = ship; XMM0 = the
//         double step accel * game_ms * 0.001, XMM2 = the current rate, XMM4 = 2^-16; the COMISS after the span writes
//         EFLAGS before any read.
//   strafe Y 0x0d1f04 / X 0x0d1f8b, 15 bytes each, continuation +15:
//         mulss xmm0,xmm6; cvtps2pd xmm0,xmm0; mulsd xmm0,xmm7; cvtpd2ps xmm4 (Y) / xmm1 (X),xmm0
//         ESI = cfg, EDI = ship; XMM0 = float game_ms, XMM6 = 20000.0, XMM7 = 0.001; Y keeps EAX/ECX/XMM5 live, X
//         ECX/EDX/XMM4; the COMISS at 0x0d1f25 / 0x0d1fac writes EFLAGS before any read.
// The apply path replays each span with the shared decision's scale: rotation multiplies XMM0's double step by 1/k^2
// before the CVTPD2PS and loads round(record+0x24 / k) in place of the MOVD; strafe multiplies the double by 1/k before
// its final CVTPD2PS. The FL step is already multiplied by the game ms, so AP's step_factor (game_ms / k^2) is not used.
