// src/proxy/chase_lead.cpp). Facts: docs/reverse-engineering/fl/chase-lead.md (offline study, then "Verified 2026-11-02
// against X3FL.exe"; verifier verification/probe/verify_chase_lead_sites_fl.py). X3FL.exe is relocatable: every value
// below is an RVA added to x3m::fl::module_base(), or a field offset. No Windows dependency (the native fixture compiles
// it).
//
// Four seams, each a six-byte whole instruction, all inside two native functions:
//   cockpit updater RVA 0x021f50 (EBX = cockpit; the chase camera's pose seam 0x0227ad dominates both the overlay call
//   0x0229c2 and the final-FOV seam 0x022cf5, verified on the updater's complete CFG), and
//   inline-overlay updater RVA 0x02c330 (ECX = O = cockpit + 0x3bc -> EBX; ESP after the prologue stays the local base P
//   at every seam; sole direct caller 0x0229c2).
//   gate      0x02c7b9  0f 84 rel32 -> 0x02cbf5  je (view-bit test), ESI = cockpit, EBX = O, EBP = overlay frame
//   publish   0x02cbe7  89 8b e0 03 00 00        mov [ebx+0x3e0],ecx: ECX = x, EDX = y, EAX = marker node
//   final FOV 0x022cf5  39 b3 40 02 00 00        cmp [ebx+0x240],esi: EBX = cockpit
//   HUD gate  0x02cc1e  0f 84 rel32 -> 0x02d019  je (view-bit test), EAX = cockpit, EBX = O
// The native solver 0x0505a0 writes its absolute world point to P+0xe0 (fifth stack argument); after pushfd/pushad the
// saved ESP slot is P-4, so the handler reads saved ESP + 0xe4. The native five-node hide helper 0x027c20 takes
// ECX = entry, plain RET (31 bytes, one rel32 call to 0x0a5740).
