// G: ESI = the script argument record, EAX = the cockpit. The stub pushes y*s, x*s (the record is not written), sets
// ECX = cockpit + 0x3bc and continues at the call of the overlay hit test base+0x02bae0 (sub esp first). EDX untouched.
// H: ESI = record, ECX = argument count (>= 3 on this path), EAX = cockpit. The stub loads x -> EDX, y -> EDI scaled and
// continues at `cmp ecx,4` (EFLAGS regenerated). The short-argument -1/-1 path jumps past the span.
// I: the worker truncates the ring offsets from XMM1 (y) and XMM4 (x); the stub converts the same way, divides each by s
