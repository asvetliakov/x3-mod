// A: 0x0de570 is ECX = object, EDX = instance (-> EDI), [EBP+8] = camera (-> EBX), `and esp,-8` frame. The 2D branch
// (instance+0x130 & 0x200, test at 0x0de5af) builds P = *(base+0x1aae4c) in ESI: P[0] = 2/Wvp, P[5] = 2/Hvp (Wvp, Hvp =
// the camera's 16.16 viewport fraction times the display record's width/height), P[12]/P[13] = the pixel offset with
// the 0.25 bias plus the anchor term +-1.0 (0x1000 left -1 before 0x2000 right +1, 0x4000 top +1 before 0x8000 bottom -1:
