// D1 movsx of the input context's +0x414/+0x416, D2 the mapped sums of base+0x21c880/0x21c884). The stub divides the two
// outgoing copies by s through a per-site 16.16 remainder pair (the AP accumulator, here with a 64-bit product so any
// dword sum is exact), then the tail replays the push. The native deltas and sums are untouched. EAX, EDX and EFLAGS are
