// ---- the mouse-delta remainder (D1, D2): the AP accumulator through a 64-bit product (exact for any dword delta) ----
inline std::int32_t callback_step(std::int32_t delta, std::uint32_t inv16, std::int32_t* acc) {
    const std::int64_t sum = std::int64_t(delta) * std::int64_t(std::int32_t(inv16)) + std::int64_t(*acc);
    *acc = std::int32_t(sum & 0xffff);
    return std::int32_t(sum >> 16); // arithmetic: floor
}

// ---- the stub encoders (position independent apart from their absolute operands) ----
namespace detail {
struct Out {
    unsigned char* p;
    unsigned n = 0;
    void b(std::initializer_list<unsigned char> bytes) {
        for (unsigned char x : bytes) p[n++] = x;
    }
    void d(std::uint32_t v) {
        for (unsigned k = 0; k < 4; ++k) p[n++] = static_cast<unsigned char>(v >> (8 * k));
    }
};
// value = (value * [fixed256] + 0x80) >> 8 for one register r (ECX = 1, EDX = 2, EDI = 7, EAX = 0): the E rounding.
inline void cursor_scale(Out& o, unsigned r, std::uint32_t fixed256) {
    o.b({0x0f, 0xaf, static_cast<unsigned char>(0x05 | (r << 3))}); // imul r,[fixed256]
    o.d(fixed256);
    if (r == 0) {
        o.b({0x05}); // add eax,0x80
    } else {
        o.b({0x81, static_cast<unsigned char>(0xc0 | r)}); // add r,0x80
    }
    o.d(0x80);
    o.b({0xc1, static_cast<unsigned char>(0xf8 | r), 0x08}); // sar r,8
}
// EAX = round(EAX / s), a tie away from zero, through EDX:EAX (the AP map label rounding).
inline void map_divide(Out& o, std::uint32_t inverse16) {
    o.b({0xf7, 0x2d}); // imul dword [inverse16]
    o.d(inverse16);
    o.b({0x81, 0xfa, 0x00, 0x00, 0x00, 0x80}); // cmp edx,0x80000000   CF = product >= 0
    o.b({0x15, 0xff, 0x7f, 0x00, 0x00});       // adc eax,0x7fff
    o.b({0x83, 0xd2, 0x00});                   // adc edx,0
    o.b({0x0f, 0xac, 0xd0, 0x10});             // shrd eax,edx,16
}
// One outgoing delta at [esp+disp] through its 16.16 remainder cell.
inline void delta_step(Out& o, unsigned char disp, std::uint32_t inverse16, std::uint32_t acc) {
    o.b({0x8b, 0x44, 0x24, disp}); // mov eax,[esp+disp]
    o.b({0xf7, 0x2d});             // imul dword [inverse16]
    o.d(inverse16);
    o.b({0x03, 0x05}); // add eax,[acc]
    o.d(acc);
    o.b({0x83, 0xd2, 0x00}); // adc edx,0
    o.b({0xa3});             // mov [acc],eax
    o.d(acc);
    o.b({0x0f, 0xac, 0xd0, 0x10}); // shrd eax,edx,16
    o.b({0x81, 0x25});             // and dword [acc],0xffff
    o.d(acc);
    o.d(0xffff);
    o.b({0x89, 0x44, 0x24, disp}); // mov [esp+disp],eax
}
inline void jmp_slot(Out& o, std::uint32_t slot) {
    o.b({0xff, 0x25}); // jmp [slot]
    o.d(slot);
}
}
