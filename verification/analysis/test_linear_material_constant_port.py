"""Host guard of the ps_3_0 constant read port in the hull light-map variants.

ps_3_0 has one constant read port: an instruction may read at most one
distinct c# (DEF excluded). wined3d does not enforce the rule, the native D3D9
runtime does (CreatePixelShader returns D3DERR_INVALIDCALL), which is how every
widened variant failed on native Windows until 2026-10-16
(docs/verification/hull-emissive-widening.md). This test builds every pixel
variant the hull light-map transformers produce from the local originals
(verification/probe/linear_material_constant_port_variants.cpp: gained and
engine-light forms, fill, gain, depth, far fade, share, widening K/B 4/4, 3/3,
8/1) and checks the rule on each, plus the v# and r# read ports.

Originals: the 137-program corpus under X3M_SHADER_PROGRAM_DIRECTORY
(default /tmp/x3-shader-sweep/programs) and the native captures under
X3M_NATIVE_CAPTURE_DIRECTORY (default /mnt/c/X3/x3-modern-captures); skipped
when neither holds a ps_*.bin (X3M_REQUIRE_SHADER_CORPUS=1 fails instead).
Generated bytes stay in a temporary folder. No game assets bundled.
"""
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
DCL, DEF, DEFI, DEFB, END, COMMENT = 31, 81, 48, 47, 0xffff, 0xfffe
NO_DESTINATION = {25, 26, 27, 28, 29, 30, 38, 39, 40, 41, 42, 43, 44, 45, 65, 96}
PORTS = ((2, 1, 'constant'), (1, 1, 'input'), (0, 3, 'temp'))


def register_type(token):
    return ((token >> 28) & 7) | ((token >> 8) & 0x18)


def port_violations(words):
    """(instruction index, dword, port, distinct registers) for each read-port breach of a ps_3_0 program."""
    rows, at, index = [], 1, 0
    while at < len(words):
        token = words[at]
        if token == END:
            break
        opcode = token & 0xffff
        if opcode == COMMENT:
            at += ((token >> 16) & 0x7fff) + 1
            continue
        count = (token >> 24) & 15
        operands = words[at + 1:at + 1 + count]
        if opcode not in (DCL, DEF, DEFI, DEFB):
            sources = operands if opcode in NO_DESTINATION else operands[1:]
            seen = {}
            for operand in sources:
                seen.setdefault(register_type(operand), set()).add(operand & 0x7ff)
            for kind, limit, name in PORTS:
                if len(seen.get(kind, ())) > limit:
                    rows.append((index, at, name, sorted(seen[kind])))
        at += count + 1
        index += 1
    return rows


def originals():
    folders = []
    for variable, default in (('X3M_SHADER_PROGRAM_DIRECTORY', '/tmp/x3-shader-sweep/programs'),
                              ('X3M_NATIVE_CAPTURE_DIRECTORY', '/mnt/c/X3/x3-modern-captures')):
        folder = Path(os.environ.get(variable, default))
        if folder.is_dir() and any(folder.glob('ps_*.bin')):
            folders.append(folder)
    return folders


class ConstantReadPortTests(unittest.TestCase):
    def test_rule_check_flags_two_constants(self):
        # mad_sat r16.w, r15.x, c210.x, -c203.y (the pre-2026-10-16 block instruction 7) breaches the port;
        # the repacked mad_sat r16.w, r15.x, c210.x, -c210.w does not.
        before = [0xffff0300, 0x04000004, 0x80180010, 0x8000000f, 0xa00000d2, 0xa15500cb, END]
        after = before[:5] + [0xa1ff00d2, END]
        self.assertEqual([row[2] for row in port_violations(before)], ['constant'])
        self.assertEqual(port_violations(after), [])

    def test_every_hull_lightmap_variant_reads_one_constant_per_instruction(self):
        folders = originals()
        if not folders:
            reason = 'no ps_*.bin originals (X3M_SHADER_PROGRAM_DIRECTORY, X3M_NATIVE_CAPTURE_DIRECTORY)'
            if os.environ.get('X3M_REQUIRE_SHADER_CORPUS') == '1':
                raise AssertionError(reason)
            self.skipTest(reason)
        compiler = shutil.which('clang++') or shutil.which('c++')
        if not compiler:
            self.fail('host C++ compiler required')
        with tempfile.TemporaryDirectory(prefix='x3-constant-port-') as temporary:
            directory = Path(temporary)
            executable = directory / 'variants'
            build = subprocess.run([compiler, '-std=c++17', '-O2', '-Wall', '-Wextra', '-Werror',
                                    str(ROOT / 'verification/probe/linear_material_constant_port_variants.cpp'),
                                    str(ROOT / 'src/renderer/linear_material.cpp'),
                                    str(ROOT / 'src/renderer/material_motion.cpp'), '-o', str(executable)],
                                   capture_output=True, text=True)
            self.assertEqual(build.returncode, 0, build.stdout + build.stderr)
            output = directory / 'out'
            output.mkdir()
            run = subprocess.run([str(executable), str(output), *map(str, folders)], capture_output=True, text=True)
            self.assertEqual(run.returncode, 0, run.stderr)
            total = re.search(r'^variants=(\d+) widened=(\d+)$', run.stdout, re.M)
            self.assertIsNotNone(total, run.stdout[-500:])
            variants, widened = int(total.group(1)), int(total.group(2))
            # Not vacuous: the originals produce gained and widened variants.
            self.assertGreater(variants, 0)
            self.assertGreater(widened, 0)
            breaches = {}
            for path in sorted(output.glob('*.bin')):
                data = path.read_bytes()
                rows = port_violations(list(struct.unpack('<%dI' % (len(data) // 4), data)))
                if rows:
                    breaches[path.name] = rows[:4]
            self.assertEqual(len(list(output.glob('*.bin'))), variants)
            print(f'constant port: {variants} variants ({widened} widened) from {len(folders)} folder(s), '
                  f'{len(breaches)} breaching', file=sys.stderr)
            if breaches:
                self.fail(f'{len(breaches)} of {variants} variants breach a read port: '
                          + repr(dict(list(breaches.items())[:6])))


if __name__ == '__main__':
    unittest.main()
