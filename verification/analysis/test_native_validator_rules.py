"""Host guard of two native D3D9 validator rules wined3d does not enforce.

1. Read ports, per shader version (DX9 SDK register tables): ps_2_0/ps_2_x read
   at most 2 distinct c#, 1 v#, 1 t#, 3 r# per instruction; ps_3_0, vs_2_x and
   vs_3_0 at most 1 c#, 1 v#, 3 r#. The occlusion pass's constants-mode vertex
   shader `mad o0, v0, c253, c252` failed CreateVertexShader on native Windows
   with id 752 (docs/verification/occlusion-cull.md, 2026-10-16).
2. No oC gap: a ps_2_x/ps_3_0 program that writes oCn writes every oC below n.
   The native validator enforces it for ps_2_0 (id 573, "no gaps"); the bolt
   far-flag variant wrote oC0 and oC2 and failed CreatePixelShader
   (docs/verification/screen-emission.md, 2026-10-16). Applied to ps_2_x and
   ps_3_0 too as a conservative guard.

Programs reached: the occlusion pass's embedded programs parsed from
src/renderer/occlusion_cull_pass.cpp (always), and every variant
linear_emission_sm1_pixel_variant authors from the SM1 profile originals found
under X3M_SHADER_PROGRAM_DIRECTORY / X3M_NATIVE_CAPTURE_DIRECTORY
(verification/probe/linear_emission_sm1_port_variants.cpp; skipped when no
profile original is present, X3M_REQUIRE_SHADER_CORPUS=1 fails instead). The
hull light-map variants get the oC rule in test_linear_material_constant_port.
Generated bytes stay in a temporary folder. No game assets bundled.
"""
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_linear_material_constant_port import COMMENT, DCL, DEF, DEFB, DEFI, END, NO_DESTINATION, originals, \
    oc_gaps, register_type

ROOT = Path(__file__).resolve().parents[2]
CONSTANT, INPUT, TEMP, TEXTURE = 2, 1, 0, 3


def port_limits(version):
    kind, major = version >> 16, (version >> 8) & 0xff
    if kind == 0xffff and major == 2:
        return ((CONSTANT, 2, 'constant'), (INPUT, 1, 'input'), (TEXTURE, 1, 'texture'), (TEMP, 3, 'temp'))
    if (kind == 0xffff and major == 3) or (kind == 0xfffe and major in (2, 3)):
        return ((CONSTANT, 1, 'constant'), (INPUT, 1, 'input'), (TEMP, 3, 'temp'))
    raise ValueError(f'no read-port table for version {version:08x}')


def port_violations(words):
    """(instruction index, dword, port, distinct registers) per read-port breach, limits by the version token."""
    limits, rows, at, index = port_limits(words[0]), [], 1, 0
    while at < len(words):
        token = words[at]
        if token == END:
            break
        opcode = token & 0xffff
        if opcode == COMMENT:
            at += ((token >> 16) & 0x7fff) + 1
            continue
        count = (token >> 24) & 15
        operands = words[at + 1:at + 1 + count]
        if opcode not in (DCL, DEF, DEFI, DEFB):
            seen = {}
            for operand in operands if opcode in NO_DESTINATION else operands[1:]:
                seen.setdefault(register_type(operand), set()).add(operand & 0x7ff)
            for kind, limit, name in limits:
                if len(seen.get(kind, ())) > limit:
                    rows.append((index, at, name, sorted(seen[kind])))
        at += count + 1
        index += 1
    return rows


def words_of(path):
    data = Path(path).read_bytes()
    return list(struct.unpack('<%dI' % (len(data) // 4), data))


def occlusion_programs():
    """{name: words} of the occlusion pass's embedded programs, parsed from the source like attach() builds them."""
    source = (ROOT / 'src/renderer/occlusion_cull_pass.cpp').read_text()

    def array(name):
        body = re.search(name + r'\[\]\s*=\s*\{([^}]*)\}', source).group(1)
        return [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)u', body)]
    programs = {name: array(name) for name in ('rect_vs_words', 'rect_mad_vs_words')}
    head = array('rect_ps_head')
    for n in range(1, 5):
        programs[f'rect_ps{n}'] = head + sum(([0x02000001, 0x800f0800 | t, 0xa0e40000] for t in range(n)), []) + [END]
    return programs


class NativeValidatorRuleTests(unittest.TestCase):
    def test_rules_flag_the_two_native_refusals(self):
        # Pre-2026-10-16 occlusion constants-mode VS: mad o0, v0, c253, c252 (two c#, id 752); the fix stages c253.
        before = [0xfffe0300, 0x0200001f, 0x80000000, 0x900f0000, 0x0200001f, 0x80000000, 0xe00f0000,
                  0x04000004, 0xe00f0000, 0x90e40000, 0xa0e400fd, 0xa0e400fc, END]
        after = before[:7] + [0x02000001, 0x800f0000, 0xa0e400fd,
                              0x04000004, 0xe00f0000, 0x90e40000, 0x80e40000, 0xa0e400fc, END]
        self.assertEqual([row[2] for row in port_violations(before)], ['constant'])
        self.assertEqual(port_violations(after), [])
        # ps_2_0 writing oC0 and oC2 (the pre-fix flag variant's outputs, id 573) has a gap at oC1.
        gap = [0xffff0200, 0x02000001, 0x800f0800, 0x80e40000, 0x02000001, 0x800f0802, 0x80e40002, END]
        fixed = gap[:4] + [0x02000001, 0x800f0801, 0x80e40000] + gap[4:]
        self.assertEqual(oc_gaps(gap), [1])
        self.assertEqual(oc_gaps(fixed), [])
        # ps_2_0 has two c# read ports: a two-constant mad is legal there.
        self.assertEqual(port_violations([0xffff0200, 0x04000004, 0x800f0000, 0x80e40000, 0xa0e40000, 0xa0e40001,
                                          END]), [])

    def test_occlusion_programs_obey_both_rules(self):
        programs = occlusion_programs()
        for name, words in programs.items():
            self.assertEqual(port_violations(words), [], name)
            if words[0] >> 16 == 0xffff:
                self.assertEqual(oc_gaps(words), [], name)
        self.assertEqual(len(programs['rect_mad_vs_words']), 16)

    def test_every_sm1_emission_variant_obeys_both_rules(self):
        folders = originals()
        compiler = shutil.which('clang++') or shutil.which('c++')
        if not compiler:
            self.fail('host C++ compiler required')
        with tempfile.TemporaryDirectory(prefix='x3-validator-rules-') as temporary:
            directory = Path(temporary)
            executable = directory / 'variants'
            build = subprocess.run([compiler, '-std=c++17', '-O2', '-Wall', '-Wextra', '-Werror',
                                    str(ROOT / 'verification/probe/linear_emission_sm1_port_variants.cpp'),
                                    str(ROOT / 'src/renderer/linear_emission_sm1.cpp'), '-o', str(executable)],
                                   capture_output=True, text=True)
            self.assertEqual(build.returncode, 0, build.stdout + build.stderr)
            output = directory / 'out'
            output.mkdir()
            run = subprocess.run([str(executable), str(output), *map(str, folders)], capture_output=True, text=True)
            self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
            total = re.search(r'^variants=(\d+) flagged=(\d+)$', run.stdout, re.M)
            self.assertIsNotNone(total, run.stdout[-500:])
            variants, flagged = int(total.group(1)), int(total.group(2))
            if not variants:
                reason = 'no SM1 emission profile original (X3M_SHADER_PROGRAM_DIRECTORY, X3M_NATIVE_CAPTURE_DIRECTORY)'
                if os.environ.get('X3M_REQUIRE_SHADER_CORPUS') == '1':
                    raise AssertionError(reason)
                self.skipTest(reason)
            self.assertGreater(flagged, 0)
            files = sorted(output.glob('*.bin'))
            self.assertEqual(len(files), variants)
            breaches = {}
            for path in files:
                words = words_of(path)
                rows = port_violations(words) + [('oC gap', gap) for gap in oc_gaps(words)]
                if rows:
                    breaches[path.name] = rows[:4]
            print(f'validator rules: {variants} SM1 emission variants ({flagged} far-flag), {len(breaches)} breaching',
                  file=sys.stderr)
            if breaches:
                self.fail(f'{len(breaches)} of {variants} variants breach a rule: ' + repr(dict(list(breaches.items())[:6])))


if __name__ == '__main__':
    unittest.main()
