  with tempfile.TemporaryDirectory() as tmp:
   out=Path(tmp); images={}
   for i in range(8):
    path=out/f'{i}.png'; path.write_bytes(f'image{i}'.encode()); images[path.name]=hashlib.sha256(path.read_bytes()).hexdigest()
   result={'schema':1,'families':{'bluewell':{'views':[{}, {}, {}]},'foggreenoutlands':{'views':[{}, {}, {}]}},'images':images}
