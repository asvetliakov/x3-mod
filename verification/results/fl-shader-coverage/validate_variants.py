#!/usr/bin/env python3
"""Native D3D9 validator over every FL variant (no device, no game).

Builds gen_fl_motion_variants.cpp against the working tree (host g++) and
../hull-widen-native-validator/native_validate.cpp (i686 MinGW), generates for
every program of the FL extension rows (motion-output-profiles-fl.json) the
variants the proxy creates (part 4a: motion, motion-depth, sun lane; part 4b:
the original-shading forms with their engine-light and strength twins and the
HDR additive hull gain), and feeds each one, plus the unmodified FL
originals as a control, to the SysWOW64 d3d9.dll
Direct3DShaderValidatorCreate9 through WSL interop. Writes validator.json
beside this script: names, sizes, verdicts and messages only. Generated bytes
stay in the scratch directory (game-derived; never commit).

usage: validate_variants.py <scratch dir> [--programs DIR]
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
VALIDATOR = HERE.parent / 'hull-widen-native-validator/native_validate.cpp'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('scratch', type=Path)
    parser.add_argument('--programs', type=Path, default=Path('/tmp/x3-fl-shader-sweep/programs'))
    arguments = parser.parse_args()
    scratch = arguments.scratch.resolve()
    if ROOT in scratch.parents or scratch == ROOT:
        raise SystemExit('the scratch directory holds game-derived bytes: keep it outside the repository')
    out = scratch / 'out'
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    extension = json.loads((HERE / 'motion-output-profiles-fl.json').read_text())
    names = sorted({'ps_' + p['ps'] for p in extension['pairs']} | {'vs_' + p['vs'] for p in extension['pairs']})
    subprocess.run(['g++', '-std=c++17', '-O2', '-Wall', '-Wextra', '-Werror', str(HERE / 'gen_fl_motion_variants.cpp'),
                    str(ROOT / 'src/renderer/material_motion.cpp'), str(ROOT / 'src/renderer/linear_material.cpp'),
                    str(ROOT / 'src/renderer/linear_emission.cpp'), '-o', str(scratch / 'gen')], check=True)
    subprocess.run(['i686-w64-mingw32-g++', '-O1', '-static', str(VALIDATOR), '-o', str(scratch / 'native_validate.exe')],
                   check=True)
    generated = subprocess.run([str(scratch / 'gen'), str(out), str(arguments.programs), *names],
                               capture_output=True, text=True)
    (scratch / 'gen.txt').write_text(generated.stdout + generated.stderr)
    if generated.returncode:
        raise SystemExit('generator failed; see %s' % (scratch / 'gen.txt'))
    forms = Counter(re.sub(r'\d$', '', form) for form in re.findall(r'^ps_\w+ form=([\w-]+) result=0 ', generated.stdout, re.M))
    largest = re.search(r'^largest=(\d+) slots=(\d+) ', generated.stdout, re.M)
    # Controls: the unmodified FL originals the variants are built from.
    for name in names:
        shutil.copy(arguments.programs / (name + '.bin'), out / (name + '-original.bin'))
    files = sorted(path.name for path in out.glob('*.bin'))
    # Negative control: the first depth variant with `add r0, c216, c217`
    # before END (two constant registers in one instruction) must be refused.
    first = next(name for name in files if name.endswith('-motion-depth.bin') and name.startswith('ps_'))
    words = list(struct.unpack('<%dI' % ((out / first).stat().st_size // 4), (out / first).read_bytes()))
    control = words[:-1] + [0x03000002, 0x800f0000, 0xa0e400d8, 0xa0e400d9, 0x0000ffff]
    (scratch / 'negative.bin').write_bytes(struct.pack('<%dI' % len(control), *control))
    negative = subprocess.run(['./native_validate.exe', 'negative.bin'], cwd=scratch, capture_output=True, text=True)
    negative_end = re.search(r'end=(\w+) messages=(\d+)', negative.stdout)
    # Batches keep each Windows command line far below its 32767-character limit.
    (scratch / 'native.txt').write_text('')
    stdout = ''
    for begin in range(0, len(files), 300):
        native = subprocess.run(['./native_validate.exe', *('out/' + name for name in files[begin:begin + 300])],
                                cwd=scratch, capture_output=True, text=True)
        stdout += native.stdout
        (scratch / 'native.txt').open('a').write(native.stdout + native.stderr)
    rows, current = [], None
    for line in stdout.splitlines():
        match = re.search(r'out/((?:vs|ps)_[0-9a-f]{16})-([\w-]+)\.bin words=(\d+) begin=(\w+)', line)
        if match:
            current = {'program': match[1], 'kind': match[2], 'words': int(match[3]), 'begin': match[4], 'messages': []}
            rows.append(current)
            continue
        match = re.search(r'msg instr=(-?\d+) id=(\d+): (.*)', line)
        if match:
            current['messages'].append({'instruction_call': int(match[1]), 'id': int(match[2]), 'text': match[3].strip()})
        match = re.search(r'end=(\w+) messages=(\d+) instruction_worst=(\w+)', line)
        if match:
            current.update(end=match[1], instruction_worst=match[3])
    if len(rows) != len(files):
        raise SystemExit('validator reported %d of %d programs; see %s' % (len(rows), len(files), scratch / 'native.txt'))
    tally = Counter((r['program'][:2], r['kind'], r.get('end'), r.get('instruction_worst'), len(r['messages'])) for r in rows)
    result = {
        'validator': 'SysWOW64 d3d9.dll Direct3DShaderValidatorCreate9 (native Windows host via WSL interop, no device)',
        'producer': str(Path(__file__).relative_to(ROOT)),
        'generator': 'gen_fl_motion_variants.cpp built against the working tree (material_motion.cpp, '
                     'linear_material.cpp, linear_emission.cpp)',
        'extension_rows': extension['pair_count'], 'programs': len(names),
        'variants': sum(r['kind'] != 'original' for r in rows), 'controls': sum(r['kind'] == 'original' for r in rows),
        'all_end_s_ok_without_messages': all(r.get('end') == '00000000' and r.get('instruction_worst') == '00000000'
                                             and not r['messages'] for r in rows),
        'negative_control': {'source': first, 'mutation': 'add r0, c216, c217 appended before END',
                             'end': negative_end[1] if negative_end else None,
                             'messages': int(negative_end[2]) if negative_end else None,
                             'refused': bool(negative_end) and negative_end[1] != '00000000'},
        # Part 4b forms applied with their kind's out-flags (lin/eng = original-shading form without/with
        # the engine light, str* = its strength twin, static/nodepth = static gain / depth off,
        # hull* = HDR additive hull gain), summed over the kinds 0-6.
        'original_shading_forms_applied': {key: count for key, count in sorted(forms.items())},
        'largest_variant_words': int(largest[1]),
        'largest_variant_slots': int(largest[2]),  # ps3_program_slots over every saved variant
        'tally': [{'stage': s, 'kind': k, 'end': e, 'instruction_worst': w, 'messages': n, 'programs': c,
                   'max_words': max(r['words'] for r in rows if (r['program'][:2], r['kind'], r.get('end'),
                                                                 r.get('instruction_worst'), len(r['messages']))
                                    == (s, k, e, w, n))}
                  for (s, k, e, w, n), c in sorted(tally.items())],
        # Every validated file passes (all_end_s_ok_without_messages); only a failing one is listed in full.
        'rows': [{k: r[k] for k in ('program', 'kind', 'words', 'end', 'instruction_worst')} |
                 ({'messages': r['messages']} if r['messages'] else {}) for r in rows
                 if r.get('end') != '00000000' or r.get('instruction_worst') != '00000000' or r['messages']],
    }
    (HERE / 'validator.json').write_text(json.dumps(result, indent=1) + '\n')
    print(json.dumps({k: v for k, v in result.items() if k != 'rows'}, indent=1))
    return 0 if result['all_end_s_ok_without_messages'] and result['negative_control']['refused'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
