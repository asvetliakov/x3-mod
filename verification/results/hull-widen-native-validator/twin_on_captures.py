#!/usr/bin/env python3
"""Host check of the widened hull variants on the 16 native captures (2026-10-16, unwidened-alpha block).

Builds gen_widen_variants.cpp against the working tree at K = B = 4 (as rerun_round3.sh) and at K = B = 3 (the
oracle's parameters), then:
- rebuilds every widened variant from its gained one with the Python twin of the block
  (verification/analysis/test_hull_emissive_widening.py reference_widened): widen from gain and swidenshare from
  sgain at K 4, widen from gain at K 3, byte for byte;
- runs the oracle's own test_widened_block_shape on the K 3 widened variants (the 137-program corpus the test
  normally walks is not on every host);
- measures the growth of each widened variant over its gained one: DWORDs, instructions and weighted SM3 slots
  (Microsoft slot table, the one verification/probe/hull_lightmap_gain_structure.cpp uses).
Writes twin_on_captures.json beside this script (counts only). Generated bytes stay in the scratch dir.
usage: PYTHONPATH=verification/probe:verification/analysis:. python3 twin_on_captures.py <scratch dir>
"""
import collections, json, shutil, struct, subprocess, sys
from pathlib import Path

V = Path(__file__).resolve().parent
R = V.parents[2]
sys.path.insert(0, str(R))
import verification.analysis.test_hull_emissive_widening as oracle

CAPTURES = '/mnt/c/X3/x3-modern-captures'
ONE = {1, 2, 4, 5, 6, 7, 8, 9, 10, 11, 12, 14, 15, 35, 42, 43, 46, 88}
TWO = {18, 39, 90, 91, 92}
THREE = {32, 36, 38, 40, 41, 93}


def words(path):
    data = Path(path).read_bytes()
    return list(struct.unpack('<%dI' % (len(data) // 4), data))


def slots(code):
    """(instructions, weighted slots) of a ps_3_0 program."""
    dims, executable, weighted, at = {}, 0, 0, 1
    while at < len(code) and code[at] != 0xffff:
        token = code[at]; op = token & 0xffff
        count = (token >> 16) & 0x7fff if op == 0xfffe else (token >> 24) & 15
        if op == 31 and (((code[at + 2] >> 28) & 7) | ((code[at + 2] >> 8) & 24)) == 10:
            dims[code[at + 2] & 0x7ff] = (code[at + 1] >> 27) & 15
        if op not in (0xfffe, 31, 81):
            executable += 1
            if op in ONE: weighted += 1
            elif op in TWO: weighted += 2
            elif op in THREE: weighted += 3
            elif op == 66: weighted += 4 if dims[code[at + 3] & 0x7ff] == 3 else 1
            else: raise ValueError('unknown SM3 slot cost, opcode %d' % op)
        at += count + 1
    return executable, weighted


def main():
    scratch = Path(sys.argv[1]).resolve()
    hashes = sorted({r['original'] for r in json.loads((V / 'result.json').read_text())['rows'] if r['kind'] == 'widen'})
    source = (V / 'gen_widen_variants.cpp').read_text().replace('#include "../../../src/renderer/linear_material.h"',
                                                                  '#include "linear_material.h"')
    result = {'captures': len(hashes), 'parameters': {}}
    out = {}
    for k in (4, 3):
        d = scratch / ('k%d' % k)
        shutil.rmtree(d, ignore_errors=True); (d / 'out').mkdir(parents=True)
        (d / 'gen.cpp').write_text(source.replace('widen{4.0f, 4.0f}', 'widen{%d.0f, %d.0f}' % (k, k)))
        subprocess.run(['g++', '-std=c++17', '-O2', '-I' + str(R / 'src/renderer'), str(d / 'gen.cpp'),
                        str(R / 'src/renderer/linear_material.cpp'), str(R / 'src/renderer/material_motion.cpp'),
                        '-o', str(d / 'gen')], check=True)
        run = subprocess.run([str(d / 'gen'), CAPTURES, str(d / 'out')] + hashes, check=True, capture_output=True, text=True)
        result['parameters']['k%d_widen_applied' % k] = run.stdout.count('widen_applied=1')
        out[k] = d / 'out'
    twin = collections.Counter()
    for h in hashes:
        for k, pairs in ((4, (('gain', 'widen'), ('sgain', 'swidenshare'))), (3, (('gain', 'widen'),))):
            for g, w in pairs:
                expected, _ = oracle.reference_widened(words(out[k] / f'{h}-{g}.bin'), k=float(k), b=float(k))
                twin[f'k{k}_{w}_{"equal" if expected == words(out[k] / f"{h}-{w}.bin") else "different"}'] += 1
    result['twin'] = dict(sorted(twin.items()))
    for h in hashes:
        shutil.copy(out[3] / f'{h}-widen.bin', out[3] / f'{h}-hlwiden-0-1.bin')
    case = oracle.HullEmissiveWideningTransformerTests('test_widened_block_shape')
    case.directory = out[3]
    case.gained = lambda: hashes
    case.test_widened_block_shape()  # raises on the first failing program
    result['block_shape_test_passed'] = len(hashes)
    growth = collections.Counter()
    for h in hashes:
        for g, w in (('gain', 'widen'), ('sgain', 'swidenshare')):
            a, b = words(out[4] / f'{h}-{g}.bin'), words(out[4] / f'{h}-{w}.bin')
            (ia, sa), (ib, sb) = slots(a), slots(b)
            growth[(w, len(b) - len(a), ib - ia, sb - sa)] += 1
    result['growth_over_gained'] = [dict(variant=w, dwords=dw, instructions=di, slots=ds, programs=c)
                                    for (w, dw, di, ds), c in sorted(growth.items())]
    (V / 'twin_on_captures.json').write_text(json.dumps(result, indent=1) + '\n')
    print(json.dumps(result))


if __name__ == '__main__':
    main()
