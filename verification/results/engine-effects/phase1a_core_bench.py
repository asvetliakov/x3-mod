#!/usr/bin/env python3
"""Engine effects phase 1a, host figures for docs/verification/engine-effects.md: the per-draw cost of the portable core
(classify + record with the c4-6 geometry + ring push; verification/analysis/test_engine_effects.py's harness, host
clang -O2, three runs) and, with the installed game tree, the C++ parse of the real engine_bodies.json generated by
tools/effects/engine_bodies.py (count, refused, bytes).

  PYTHONPATH=verification/probe python3 verification/results/engine-effects/phase1a_core_bench.py
"""
import platform
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'verification/analysis'))
from verification.analysis import test_engine_effects as t  # noqa: E402

with tempfile.TemporaryDirectory(prefix='x3-engine-effects-bench-') as directory:
    exe = t.build(Path(directory))
    print('host', platform.machine(), platform.system())
    for _ in range(3):
        lines = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout.splitlines()
        print(next(l for l in lines if l.startswith('BENCH')))
    if (t.bob1.DEFAULT_GAME / 'addon/06.cat').exists():
        table = t.eb.generate(t.bob1.DEFAULT_GAME)
        path = Path(directory) / 'engine_bodies.json'
        path.write_text(t.eb.dumps(table))
        first = subprocess.run([str(exe), 'parse', str(path)], capture_output=True, text=True).stdout.splitlines()[0]
        print(first, 'bytes=%d' % path.stat().st_size, 'generator_bodies=%d' % len(table['bodies']), 'missing=%d' % len(table['missing']))
    else:
        print('installed game tree unavailable: real-table parse skipped')
